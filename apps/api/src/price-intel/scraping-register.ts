import type {
  AutomatedAccessFinding,
  PriceProduct,
  ProxyClass,
  ScrapeVendor,
  SourcePolicyBasis,
  SourcePolicyStatus,
} from '@suskii/shared';

import type { PrismaService } from '../infra/prisma.service';

/** One site of the register: what is read, on what basis, how, and when that was decided. */
export interface ScrapingRegisterRow {
  domain: string;
  name: string;
  status: SourcePolicyStatus;
  basis: SourcePolicyBasis | null;
  basisReference: string | null;
  robots: AutomatedAccessFinding;
  terms: AutomatedAccessFinding;
  products: PriceProduct[];
  vendors: ScrapeVendor[];
  maxProxyClass: ProxyClass;
  requestsPerMinute: number;
  decidedAt: string | null;
}

/** Every listed site with its status and basis, by domain. */
export async function scrapingRegisterRows(
  prisma: Pick<PrismaService, 'priceSource'>,
): Promise<ScrapingRegisterRow[]> {
  const rows = await prisma.priceSource.findMany({
    include: { policy: true },
    orderBy: { domain: 'asc' },
  });
  return rows.flatMap((row) =>
    row.policy
      ? [
          {
            domain: row.domain,
            name: row.name,
            status: row.policy.status,
            basis: row.policy.basis as SourcePolicyBasis | null,
            basisReference: row.policy.basisReference,
            robots: row.policy.robots as AutomatedAccessFinding,
            terms: row.policy.terms as AutomatedAccessFinding,
            products: row.products as PriceProduct[],
            vendors: row.policy.vendors as ScrapeVendor[],
            maxProxyClass: row.policy.maxProxyClass as ProxyClass,
            requestsPerMinute: row.policy.requestsPerMinute,
            decidedAt: row.policy.decidedAt?.toISOString() ?? null,
          },
        ]
      : [],
  );
}

const BASIS_TEXT: Record<SourcePolicyBasis, string> = {
  licence: "A licence: the site's owner sells or grants access to this data.",
  permission: "Permission: the site's owner agreed in writing to automated reading.",
  public_data_assessment:
    'An assessment on file that the data is public, not personal, and that neither the robots file nor the terms disallow reading it.',
  counsel_note: "Counsel's written note that reading this site is acceptable.",
};

const FINDING_TEXT: Record<AutomatedAccessFinding, string> = {
  unknown: 'nobody has read it yet; the site cannot be approved',
  allowed: 'it allows automated access',
  silent: 'it says nothing about automated access',
  disallowed: 'it disallows automated access; only a licence or a permission can approve the site',
};

/** The part of the page that never depends on the registry: what the register is and means. */
export function scrapingRegisterPreamble(): string {
  return [
    '# Scraping register',
    '',
    '<!-- Generated by `pnpm --filter @suskii/api price-intel:register`. Do not edit by hand. -->',
    '',
    'Every website price intelligence may read, or was told never to read, with the reason it',
    'may (ADR-102). The registry in the database is the source: this page is a copy of it, made',
    'by the command above against one environment, for counsel and for audits. The console shows',
    'the same rows live under Data sources.',
    '',
    'What the rows mean:',
    '',
    '- **Status.** `review`: listed, not decided; nothing real is read (only the mock vendor',
    '  answers, and production has no mock). `approved`: read under the rules in its row.',
    '  `blocked`: never read, by any vendor, in any environment.',
    '- **Basis.** Why an approved site may be read, with where that is written down:',
    ...Object.entries(BASIS_TEXT).map(([basis, text]) => `  - \`${basis}\`: ${text}`),
    '- **Robots file and terms.** What each says, as a person recorded it:',
    ...Object.entries(FINDING_TEXT).map(([finding, text]) => `  - \`${finding}\`: ${text}`),
    '- **Highest proxy class.** The most a read may use to reach the site: `none` (our own',
    '  address), `datacenter`, `residential` or `unblocker` (access a vendor manages). The',
    '  approver sets it; the router never goes above it.',
    '',
    'Approving a site, sending it back to review and blocking it are staff actions in the',
    'console, with a second authenticator check for approval, and each is in the audit log with',
    'who did it. Changing what an approver agreed to (the vendors, the proxy class, the findings,',
    'the page addresses, the rate) sends an approved site back to review.',
    '',
    'Only public, non-personal price data is read: no page behind a sign-in, no account, no',
    'reviewer or contact details.',
    '',
  ].join('\n');
}

const cell = (value: string): string =>
  value
    .replace(/[\r\n]+/g, ' ')
    .replace(/\|/g, '\\|')
    .trim();

/**
 * `docs/legal/scraping-register.md` from the registry. `generatedAt` and `environment` say which
 * registry and when; the committed page is the rendering of an empty one.
 */
export function renderScrapingRegister(register: {
  rows: readonly ScrapingRegisterRow[];
  generatedAt: string | null;
  environment: string | null;
}): string {
  const lines = [scrapingRegisterPreamble(), '## Sites', ''];
  if (register.generatedAt) {
    lines.push(
      `Copied on ${register.generatedAt.slice(0, 10)}${
        register.environment ? ` from the ${cell(register.environment)} environment` : ''
      }.`,
      '',
    );
  }
  if (register.rows.length === 0) {
    lines.push('No site is listed. Nothing is read until a site is listed and approved.', '');
    return lines.join('\n');
  }
  lines.push(
    '| Domain | Name | Status | Basis | Reference | Robots file | Terms | Products | Vendors, in order | Highest proxy class | Requests a minute | Decided |',
    '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |',
  );
  for (const row of register.rows) {
    lines.push(
      `| ${[
        cell(row.domain),
        cell(row.name),
        row.status,
        row.basis ?? '-',
        row.basisReference ? cell(row.basisReference) : '-',
        row.robots,
        row.terms,
        row.products.join(', '),
        row.vendors.join(', '),
        row.maxProxyClass,
        String(row.requestsPerMinute),
        row.decidedAt ? row.decidedAt.slice(0, 10) : '-',
      ].join(' | ')} |`,
    );
  }
  const count = (status: SourcePolicyStatus): number =>
    register.rows.filter((row) => row.status === status).length;
  lines.push(
    '',
    `${count('approved')} approved, ${count('review')} in review, ${count('blocked')} blocked.`,
    '',
  );
  return lines.join('\n');
}
