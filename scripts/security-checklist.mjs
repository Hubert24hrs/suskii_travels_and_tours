#!/usr/bin/env node
/**
 * Builds docs/security/checklist.md from the OWASP requirement lists and the reviewed mapping
 * (docs/security/standards). With --check it writes nothing and fails when:
 *
 * - a requirement has no mapping, or the mapping names an unknown id;
 * - a status is unknown, or a non-met status has no note;
 * - a met requirement has no evidence, or an accepted one does not cite ADR-048;
 * - an evidence path does not exist;
 * - the committed checklist differs from what the mapping produces.
 *
 *   node scripts/security-checklist.mjs           # regenerate
 *   node scripts/security-checklist.mjs --check   # CI
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const STANDARDS = join(ROOT, 'docs', 'security', 'standards');
const OUTPUT = join(ROOT, 'docs', 'security', 'checklist.md');
const ACCEPTED_RECORD = 'docs/decisions/ADR-048-security-verification-and-accepted-risks.md';
const STATUS_ORDER = ['met', 'partial', 'deployment', 'accepted', 'not-applicable'];
const STATUS_LABEL = {
  met: 'Met',
  partial: 'Partial',
  deployment: 'Deployment',
  accepted: 'Accepted',
  'not-applicable': 'N/A',
};

const readJson = (name) => JSON.parse(readFileSync(join(STANDARDS, name), 'utf8'));
const asvs = readJson('asvs-5.0.0-l1-l2.json');
const masvs = readJson('masvs.json');
const mapping = readJson('mapping.json');

const items = [
  ...asvs.requirements.map((r) => ({ ...r, group: r.chapter, standard: 'asvs' })),
  ...masvs.controls.map((c) => ({ ...c, level: null, group: c.group, standard: 'masvs' })),
];

function validate() {
  const problems = [];
  const known = new Set(items.map((item) => item.id));
  for (const item of items) {
    const entry = mapping.requirements[item.id];
    if (!entry) {
      problems.push(`${item.id}: no mapping`);
      continue;
    }
    if (!STATUS_ORDER.includes(entry.status)) {
      problems.push(`${item.id}: unknown status "${entry.status}"`);
    }
    if (entry.status !== 'met' && !entry.note?.trim()) problems.push(`${item.id}: needs a note`);
    if (entry.status === 'met' && entry.evidence.length === 0) {
      problems.push(`${item.id}: met without evidence`);
    }
    if (entry.status === 'accepted' && !entry.evidence.includes(ACCEPTED_RECORD)) {
      problems.push(`${item.id}: accepted without ${ACCEPTED_RECORD}`);
    }
    for (const path of entry.evidence) {
      if (!existsSync(join(ROOT, path))) problems.push(`${item.id}: ${path} does not exist`);
    }
  }
  for (const id of Object.keys(mapping.requirements)) {
    if (!known.has(id)) problems.push(`${id}: not in the standards`);
  }
  return problems;
}

/** Table cells: no pipes or line breaks. */
const cell = (text) => text.replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ');
const evidenceCell = (paths) => paths.map((path) => `\`${path}\``).join('<br>');

function counts(list) {
  const result = Object.fromEntries(STATUS_ORDER.map((status) => [status, 0]));
  for (const item of list) result[mapping.requirements[item.id].status] += 1;
  return result;
}

function summaryRow(name, list) {
  const c = counts(list);
  return `| ${name} | ${list.length} | ${STATUS_ORDER.map((status) => c[status]).join(' | ')} |`;
}

function render() {
  const groups = new Map();
  for (const item of items) {
    const key = `${item.standard}:${item.group}`;
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push(item);
  }
  const asvsItems = items.filter((item) => item.standard === 'asvs');
  const masvsItems = items.filter((item) => item.standard === 'masvs');
  const header = `| Area | Total | ${STATUS_ORDER.map((s) => STATUS_LABEL[s]).join(' | ')} |`;
  const rule = `| --- | ---: | ${STATUS_ORDER.map(() => '---:').join(' | ')} |`;

  const lines = [
    '<!-- Generated by scripts/security-checklist.mjs from docs/security/standards/mapping.json. Do not edit by hand. -->',
    '',
    '# Security verification checklist',
    '',
    `Every OWASP ASVS 5.0.0 level 1 and 2 requirement (${asvsItems.length}) and every MASVS control (${masvsItems.length}), with its status in this repository and the evidence for it. Reviewed ${mapping.reviewed}.`,
    '',
    'Statuses:',
    '',
    ...STATUS_ORDER.map((status) => `- **${STATUS_LABEL[status]}**: ${mapping.statuses[status]}`),
    '',
    'To change a status, edit `docs/security/standards/mapping.json` and run `pnpm security:checklist`. CI runs it with `--check`, so the mapping, the evidence paths and this page cannot drift apart. Accepted deviations and their compensating controls are recorded in ADR-048.',
    '',
    '## Summary',
    '',
    header,
    rule,
    summaryRow('ASVS 5.0.0 (L1 + L2)', asvsItems),
    summaryRow('MASVS 2.x', masvsItems),
    '',
    '### By chapter',
    '',
    header,
    rule,
    ...[...groups.values()].map((list) => summaryRow(list[0].group, list)),
    '',
    '## Open items',
    '',
    'Everything that is not met or not applicable, for planning:',
    '',
    '| ID | Status | Note |',
    '| --- | --- | --- |',
    ...items
      .filter((item) =>
        ['partial', 'deployment', 'accepted'].includes(mapping.requirements[item.id].status),
      )
      .map((item) => {
        const entry = mapping.requirements[item.id];
        return `| ${item.id} | ${STATUS_LABEL[entry.status]} | ${cell(entry.note)} |`;
      }),
    '',
  ];

  for (const list of groups.values()) {
    const first = list[0];
    lines.push(`## ${first.standard === 'asvs' ? 'ASVS' : 'MASVS'}: ${first.group}`, '');
    if (first.standard === 'asvs') {
      lines.push(
        '| ID | L | Requirement | Status | Evidence | Note |',
        '| --- | --- | --- | --- | --- | --- |',
      );
    } else {
      lines.push('| ID | Control | Status | Evidence | Note |', '| --- | --- | --- | --- | --- |');
    }
    for (const item of list) {
      const entry = mapping.requirements[item.id];
      const common = `${STATUS_LABEL[entry.status]} | ${evidenceCell(entry.evidence)} | ${cell(entry.note)}`;
      lines.push(
        first.standard === 'asvs'
          ? `| ${item.id} | ${item.level} | ${cell(item.text)} | ${common} |`
          : `| ${item.id} | ${cell(item.text)} | ${common} |`,
      );
    }
    lines.push('');
  }

  lines.push(
    '## Attribution',
    '',
    `Requirement texts: ${asvs.source}, and ${masvs.source}. Both are licensed under ${asvs.license}; this page, which adapts them, is shared under the same license.`,
    '',
  );
  return lines.join('\n');
}

const problems = validate();
if (problems.length > 0) {
  process.stderr.write(
    `security checklist: ${problems.length} problem(s)\n${problems.map((p) => `  - ${p}`).join('\n')}\n`,
  );
  process.exit(1);
}
const output = render();
if (process.argv.includes('--check')) {
  const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, 'utf8') : '';
  if (current !== output) {
    process.stderr.write(
      'docs/security/checklist.md is out of date: run pnpm security:checklist\n',
    );
    process.exit(1);
  }
  process.stdout.write(`security checklist: ${items.length} requirements mapped, up to date\n`);
} else {
  writeFileSync(OUTPUT, output);
  process.stdout.write(`wrote docs/security/checklist.md (${items.length} requirements)\n`);
}
